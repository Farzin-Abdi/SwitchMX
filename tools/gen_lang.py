#!/usr/bin/env python3
"""Builds source/lang_xx.cpp from the English key list and one translation file per language.

keys.txt: one English text per line, written as in the C++ source (quotes as \\", line breaks as \\n).
xx.txt:   "index<TAB>translation" per line, in the same order; "=" keeps the English.
"""
import re, sys, os

def main(keys_path, tr_dir, out_dir):
    keys = open(keys_path, encoding='utf-8').read().split('\n')
    codes = ['fa', 'ar', 'es', 'fr', 'de', 'it', 'pt', 'ru', 'tr', 'zh', 'ja', 'ko']
    ok = True
    for code in codes:
        rows = []
        path = os.path.join(tr_dir, code + '.txt')
        if os.path.exists(path):
            lines = [l for l in open(path, encoding='utf-8').read().split('\n') if l.strip()]
            if len(lines) != len(keys):
                print(f'{code}: {len(lines)} lines for {len(keys)} keys'); ok = False
            for n, line in enumerate(lines):
                idx, _, text = line.partition('\t')
                if not idx.isdigit() or int(idx) != n:
                    print(f'{code}: line {n + 1} is numbered {idx!r}'); ok = False; break
                if text == '=' or text == keys[n]:
                    continue
                if re.search(r'(?<!\\)"', text):
                    print(f'{code}: unescaped quote at {n}: {text}'); ok = False
                # every {k} in the English must be in the translation
                for ph in set(re.findall(r'\{\d\}', keys[n])):
                    if ph not in text:
                        print(f'{code}: {n} lacks {ph}: {text}'); ok = False
                rows.append((keys[n], text))
        out = ['// Generated by tools/gen_lang.py from the translation list. Edit that, not this file.',
               '#include <cstddef>', '', 'namespace lang {', f'extern const char* const k_{code}[][2];',
               f'extern const size_t k_{code}_count;', f'const char* const k_{code}[][2] = {{']
        for k, t in rows:
            out.append(f'    {{"{k}", "{t}"}},')
        if not rows:
            out.append('    {"", ""},')
        out.append('};')
        out.append(f'const size_t k_{code}_count = {len(rows)};')
        out.append('}  // namespace lang')
        open(os.path.join(out_dir, f'lang_{code}.cpp'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
        print(f'{code}: {len(rows)} texts')
    return ok

if __name__ == '__main__':
    sys.exit(0 if main(*sys.argv[1:4]) else 1)
