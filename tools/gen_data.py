"""Generates source/font_data.c and source/codepages.c (run from the repo root)."""
import codecs

def c_array(name, data):
    out = [f"const unsigned char {name}[] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    out.append("};")
    out.append(f"const unsigned int {name}_size = {len(data)};")
    return "\n".join(out)

