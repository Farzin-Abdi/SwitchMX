// Dev tool: turns hacBrewPack's archives, made with throwaway keys, into the plain templates in
// source/forwarder_data.c. Usage: gen_forwarder_data keysfile program.nca control.nca meta.nca > out.c
#include <cstdio>
#include <cstring>
#include <string>
#include <vector>

#include "forwarder.hpp"
#include "minicrypto.h"

static std::vector<uint8_t> readAll(const char* path) {
    FILE* f = fopen(path, "rb");
    if (!f) {
        perror(path);
        exit(1);
    }
    std::vector<uint8_t> d;
    uint8_t buf[65536];
    size_t n;
    while ((n = fread(buf, 1, sizeof buf, f)) > 0) d.insert(d.end(), buf, buf + n);
    fclose(f);
    return d;
}

static void xtsDecrypt(const uint8_t key[32], uint8_t* data, size_t len) {
    mc_aes dataKey, tweakKey;
    mc_aes_init(&dataKey, key, 16);
    mc_aes_init(&tweakKey, key + 16, 16);
    for (size_t sector = 0; sector * 0x200 < len; sector++) {
        uint8_t iv[16] = {}, tweak[16];
        for (int i = 0; i < 8; i++) iv[15 - i] = (uint8_t)((uint64_t)sector >> (i * 8));
        mc_aes_encrypt_block(&tweakKey, iv, tweak);
        uint8_t* s = data + sector * 0x200;
        for (size_t off = 0; off < 0x200; off += 16) {
            uint8_t block[16];
            for (int i = 0; i < 16; i++) block[i] = s[off + i] ^ tweak[i];
            mc_aes_decrypt_block(&dataKey, block, block);
            for (int i = 0; i < 16; i++) s[off + i] = block[i] ^ tweak[i];
            uint8_t carry = 0;
            for (int i = 0; i < 16; i++) {
                uint8_t next = tweak[i] >> 7;
                tweak[i] = (uint8_t)(tweak[i] << 1) | carry;
                carry = next;
            }
            if (carry) tweak[0] ^= 0x87;
        }
    }
}

static void plain(std::vector<uint8_t>& nca, const forwarder::Keys& keys) {
    xtsDecrypt(keys.header, nca.data(), 0xC00);
    if (memcmp(nca.data() + 0x200, "NCA3", 4) != 0) {
        fprintf(stderr, "Not an NCA3, or wrong keys\n");
        exit(1);
    }
    uint8_t sectionKey[16];
    mc_aes kaek;
    mc_aes_init(&kaek, keys.keyArea, 16);
    mc_aes_decrypt_block(&kaek, nca.data() + 0x320, sectionKey);
    mc_aes aes;
    mc_aes_init(&aes, sectionKey, 16);
    for (int s = 0; s < 4; s++) {
        const uint8_t* e = nca.data() + 0x240 + s * 16;
        uint64_t start = (uint64_t)(e[0] | e[1] << 8 | e[2] << 16 | e[3] << 24) * 0x200;
        uint64_t end = (uint64_t)(e[4] | e[5] << 8 | e[6] << 16 | e[7] << 24) * 0x200;
        const uint8_t* fs = nca.data() + 0x400 + s * 0x200;
        if (end <= start || fs[4] != 3) continue;
        uint8_t ctr[16], stream[16];
        for (int i = 0; i < 8; i++) ctr[i] = fs[0x140 + 7 - i];
        for (uint64_t off = start; off < end; off += 16) {
            uint64_t n = off >> 4;
            for (int i = 0; i < 8; i++) ctr[15 - i] = (uint8_t)(n >> (i * 8));
            mc_aes_encrypt_block(&aes, ctr, stream);
            for (int i = 0; i < 16 && off + i < end; i++) nca[off + i] ^= stream[i];
        }
    }
    memset(nca.data() + 0x300, 0, 0x40);
}

static void emit(const char* name, const std::vector<uint8_t>& d) {
    printf("const unsigned int %sSize = %zu;\nconst unsigned char %s[] = {", name, d.size(), name);
    for (size_t i = 0; i < d.size(); i++) printf("%s%u,", i % 32 == 0 ? "\n" : "", d[i]);
    printf("\n};\n\n");
}

int main(int argc, char** argv) {
    if (argc != 5 && argc != 6) return 1;
    forwarder::Keys keys;
    std::string err;
    if (!forwarder::loadKeys(argv[1], keys, err)) {
        fprintf(stderr, "%s\n", err.c_str());
        return 1;
    }
    auto program = readAll(argv[2]), control = readAll(argv[3]), meta = readAll(argv[4]);
    plain(program, keys);
    plain(control, keys);
    plain(meta, keys);
    // The same launcher for firmware before 19.0.0, whose permissions use the older layout.
    std::vector<uint8_t> legacy = argc == 6 ? readAll(argv[5]) : program;
    plain(legacy, keys);
    printf("// Generated by tools/gen_forwarder_data.sh. Holds no keys.\n\n");
    emit("g_fwdProgram", program);
    emit("g_fwdControl", control);
    emit("g_fwdMeta", meta);
    emit("g_fwdProgramLegacy", legacy);
}
