pages = [1250, 1251, 1252, 1253, 1254, 1255, 1256]
with open("source/codepages.c", "w") as f:
    f.write("// Generated by tools/gen_data.py: bytes 0x80-0xFF of Windows code pages as Unicode.\n")
    f.write("const unsigned short g_codepageTables[%d][128] = {\n" % len(pages))
    for cp in pages:
        vals = []
        for b in range(0x80, 0x100):
            try:
                vals.append(ord(bytes([b]).decode(f"cp{cp}")))
            except UnicodeDecodeError:
                vals.append(0xFFFD)
        f.write("    {" + ",".join(hex(v) for v in vals) + "},  // cp%d\n" % cp)
    f.write("};\n")
